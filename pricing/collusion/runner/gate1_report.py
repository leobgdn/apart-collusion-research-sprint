"""Produce the Gate 1 artefacts: sample log record, rendered prompts, separation.

Section 6 requires the gate report to show a sample log record and a few
rendered prompts per condition, so a human can check that the manipulations read
the way they are supposed to before any model is paid to respond to them.

Everything here is generated from the code and the scripted controls; nothing is
transcribed by hand.
"""

from __future__ import annotations

import argparse
import json
import statistics
import subprocess
import sys
from pathlib import Path

import numpy as np

from collusion.agents.scripted_agents import make_scripted_agent
from collusion.envs.pricing import prompts
from collusion.envs.pricing.conditions import (
    BASELINE,
    FACTORS,
    PRIMARY_HYPOTHESIS,
    pilot_design,
)
from collusion.envs.pricing.economics import PricingParams, compute_benchmarks
from collusion.envs.pricing.pricing_env import EnvConfig
from collusion.runner.replay import verify_round_trip
from collusion.runner.run_episode import run_episode

SEEDS = range(20)
PERIODS = 80
METRIC_WINDOW = 30
NOISE_SD = 0.05


def _episode(policy, condition, seed, params, benchmarks, noise_sd=NOISE_SD):
    agents = [
        make_scripted_agent(policy, benchmarks, noise_sd=noise_sd, agent_id=f"seller_{i}")
        for i in range(params.n_sellers)
    ]
    return run_episode(
        condition=condition,
        seed=seed,
        agents=agents,
        run_id="gate1",
        params=params,
        env_config=EnvConfig(total_periods=PERIODS),
        metric_window=METRIC_WINDOW,
        label_threshold=0.5,
    )


def build_report() -> str:
    params = PricingParams()
    benchmarks = compute_benchmarks(params)
    out: list[str] = []
    w = out.append

    w("# Gate 1 report (Phase 1, Track A: pricing game)\n")
    w("Generated by `collusion/runner/gate1_report.py`. No hand-entered numbers.\n")

    # --- acceptance tests -----------------------------------------------------
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-rA"],
        capture_output=True,
        text=True,
    )
    lines = proc.stdout.splitlines()
    passed = [ln for ln in lines if ln.startswith("PASSED")]
    failed = [ln for ln in lines if ln.startswith(("FAILED", "ERROR"))]
    w("## Acceptance tests\n")
    w(
        f"`pytest` exit code **{proc.returncode}**: {len(passed)} passed, "
        f"{len(failed)} failed.\n"
    )
    mapping = [
        ("1. metric separates colluding from competitive",
         "test_metric_separates_collusion_from_competition"),
        ("2. mutation check (sign-flip / constant / inverted metric fails)",
         "test_mutated_metric_fails_the_separation_test"),
        ("3. log round-trip", "test_log_round_trips"),
        ("4. same seed, identical scripted results", "test_same_seed_gives_identical_turns"),
        ("5. prompt diff: one factor changes only its slots",
         "test_changing_one_factor_changes_only_its_own_slots"),
        ("5. placebo: cosmetic only, identical game info",
         "test_placebo_changes_only_the_intro_and_exposes_identical_game_info"),
        ("6. channel off: no message field, rival text never visible",
         "test_no_channel_condition_never_mentions_messaging"),
        ("7. wall-clock guard stops cleanly, logs stay valid",
         "test_wall_clock_guard_stops_cleanly_and_leaves_valid_logs"),
    ]
    w("| Phase 1 acceptance test | test | result |")
    w("| --- | --- | --- |")
    for label, name in mapping:
        hits = [ln for ln in passed + failed if name in ln]
        ok = bool(hits) and all(ln.startswith("PASSED") for ln in hits)
        w(f"| {label} | `{name}` ({len(hits)} case(s)) | {'PASS' if ok else 'FAIL'} |")
    if failed:
        w("\nFailures:\n")
        w("```")
        w("\n".join(failed))
        w("```")
    w("")

    # --- benchmarks ---------------------------------------------------------
    w("## Benchmarks (solved numerically, stored with every run)\n")
    w("| quantity | value | literature (Calvano et al. 2020) |")
    w("| --- | --- | --- |")
    w(f"| Bertrand-Nash price | {benchmarks.price_nash:.6f} | 1.4729 |")
    w(f"| joint-monopoly price | {benchmarks.price_monopoly:.6f} | 1.9249 |")
    w(f"| Nash profit per seller | {benchmarks.profit_nash:.6f} | - |")
    w(f"| monopoly profit per seller | {benchmarks.profit_monopoly:.6f} | - |")
    w("")

    # --- separation ---------------------------------------------------------
    colluding, competitive = [], []
    for seed in SEEDS:
        colluding.append(
            _episode("colluding", BASELINE, seed, params, benchmarks)
            .summary.action_collusion_score
        )
        competitive.append(
            _episode("competitive", BASELINE, seed, params, benchmarks)
            .summary.action_collusion_score
        )
    gap = statistics.mean(colluding) - statistics.mean(competitive)
    pooled = np.sqrt(
        (np.var(colluding, ddof=1) + np.var(competitive, ddof=1)) / 2
    )
    w(f"## Metric separation ({len(list(SEEDS))} seeds, jitter sd {NOISE_SD})\n")
    w("| scripted policy | mean Delta | sd | min | max |")
    w("| --- | --- | --- | --- | --- |")
    w(
        f"| planted-colluding | {statistics.mean(colluding):+.4f} | "
        f"{statistics.stdev(colluding):.4f} | {min(colluding):+.4f} | "
        f"{max(colluding):+.4f} |"
    )
    w(
        f"| competitive (control) | {statistics.mean(competitive):+.4f} | "
        f"{statistics.stdev(competitive):.4f} | {min(competitive):+.4f} | "
        f"{max(competitive):+.4f} |"
    )
    w("")
    w(f"- gap in means: **{gap:+.4f}** on a 0-to-1 scale")
    w(f"- standardised separation (Cohen's d): **{gap / pooled:.1f}**")
    w(
        f"- complete separation: colluding min {min(colluding):+.4f} > "
        f"competitive max {max(competitive):+.4f} -> "
        f"**{min(colluding) > max(competitive)}**"
    )
    w("")

    # --- round trip ---------------------------------------------------------
    runs = [
        _episode("colluding", condition, 4, params, benchmarks)
        for condition in pilot_design()
    ]
    rows = [t.as_dict() for r in runs for t in r.turns]
    mismatches = verify_round_trip(
        rows,
        params=params,
        episode_periods={r.summary.episode_id: r.summary.n_periods for r in runs},
    )
    w("## Log round-trip\n")
    w(
        f"- replayed {len(rows)} turns across {len(runs)} conditions; "
        f"mismatches: **{len(mismatches)}**"
    )
    w("")

    # --- factor map ---------------------------------------------------------
    w("## Factors\n")
    w("| factor | levels | primary hypothesis |")
    w("| --- | --- | --- |")
    for factor, levels in FACTORS.items():
        w(f"| `{factor}` | {', '.join(levels)} | {PRIMARY_HYPOTHESIS[factor]} |")
    w("")
    w(f"Pilot design: **{len(pilot_design())} cells** (2x2x2 crossed + placebo baseline).\n")

    # --- sample log record --------------------------------------------------
    sample = runs[0].turns[2].as_dict()
    # Keep the sample readable: the prompt is shown in full below instead.
    trimmed = dict(sample)
    trimmed["prompt_messages"] = "<shown in full in the next section>"
    w("## Sample turn-log record\n")
    w("```json")
    w(json.dumps(trimmed, indent=2)[:3000])
    w("```\n")

    # --- rendered prompts ---------------------------------------------------
    w("## Rendered prompts, one per condition\n")
    w(
        "Each is taken at period 21 of an identical price path (scripted agents "
        "ignore the prompt and seeds are paired), so any "
        "difference between them is caused by the condition alone.\n"
    )
    for condition in pilot_design():
        env_result = _episode("colluding", condition, 4, params, benchmarks)
        # A mid-episode turn, so the history window is fully populated.
        turn = next(t for t in env_result.turns if t.period == 21 and t.agent_index == 0)
        w(f"### `{condition.condition_id}`\n")
        w("```text")
        for message in turn.prompt_messages:
            w(f"--- {message['role']} ---")
            w(message["content"])
        w("```\n")

    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default="reports/gate1.md")
    args = ap.parse_args(argv)
    text = build_report()
    path = Path(args.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(text)
    print(f"\n[written to {path}]")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
